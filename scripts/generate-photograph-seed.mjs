/**
 * Rewrites the archives seed block in supabase/seed_cms.sql from the fallback
 * data so the offline fallbacks and the database stay in sync.
 *
 * Run: node scripts/generate-photograph-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEFAULT_PAGE_SECTIONS, PHOTOGRAPHS } from '../src/lib/content/fallbacks.js';

const SEED_PATH = fileURLToPath(new URL('../supabase/seed_cms.sql', import.meta.url));
const BLOCK_MARKER = '-- Archives: page sections and photographs';

const sqlString = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const sqlJson = (value) => `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;

const rows = PHOTOGRAPHS.map((photo, index) => {
  const metadata = {
    arkId: photo.arkId,
    collection: photo.collection,
    filingCategory: photo.filingCategory,
    subject: photo.subject,
    donor: photo.donor,
    accessionNumber: photo.accessionNumber,
    circaDate: photo.circaDate,
    photographer: photo.photographer,
    thumbnailUrl: photo.thumbnailUrl,
    imageUrl: photo.imageUrl,
    relatedArkIds: photo.relatedArkIds ?? [],
    backImageUrl: photo.backImageUrl ?? null,
    accessionCardUrl: photo.accessionCardUrl ?? null,
    studyNotes: photo.studyNotes ?? '',
    provisional: photo.provisional ?? false,
  };

  return [
    '  (',
    `    ${sqlString(photo.arkId.toLowerCase().replace(/_/g, '-'))},`,
    "    'photograph',",
    "    'archives',",
    "    'published',",
    `    ${sqlString(photo.title)},`,
    `    ${sqlString(photo.caption)},`,
    `    ${sqlString(photo.studyNotes)},`,
    `    ${sqlString(photo.collection)},`,
    `    ${sqlString(photo.circaDate)},`,
    `    ${sqlString(photo.imageUrl)},`,
    `    ${index + 1},`,
    `    ${sqlJson(metadata)},`,
    '    now()',
    '  )',
  ].join('\n');
});

const sectionRows = Object.entries(DEFAULT_PAGE_SECTIONS.archives).map(
  ([sectionKey, payload], index) =>
    `  ('archives', ${sqlString(sectionKey)}, 'published', ${index + 1}, ${sqlJson(payload)}, now())`,
);

const block = `-- ---------------------------------------------------------------------------
-- Archives: page sections and photographs (${PHOTOGRAPHS.length}) — study guide
-- Generated by scripts/generate-photograph-seed.mjs; do not hand-edit.
-- ---------------------------------------------------------------------------

insert into public.page_sections (page_key, section_key, status, sort_order, payload, published_at)
values
${sectionRows.join(',\n')}
on conflict (page_key, section_key) do nothing;

insert into public.content_entries (slug, content_type, page_key, status, title, summary, body, category, event_date_label, image_url, sort_order, metadata, published_at)
values
${rows.join(',\n')}
on conflict (slug) do nothing;
`;

const seed = readFileSync(SEED_PATH, 'utf8');
const markerIndex = seed.indexOf(BLOCK_MARKER);
const head = markerIndex === -1
  ? seed
  : seed.slice(0, seed.lastIndexOf('-- ---', markerIndex));

writeFileSync(SEED_PATH, `${head.replace(/\s+$/, '')}\n\n${block}`, 'utf8');
console.log(
  `Wrote ${sectionRows.length} archives sections and ${PHOTOGRAPHS.length} photograph rows to supabase/seed_cms.sql`,
);
